import type { ApprovalDto, LoadTestDto } from '@friday/shared';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { api } from '../../lib/api';
import { ApprovalCard } from '../ApprovalCard';
import { LoadTargetSettings } from '../LoadTargetSettings';
import { LoadTestCard } from '../LoadTestCard';
import { toolLabel } from '../ToolActivity';

afterEach(() => {
  cleanup();
  vi.restoreAllMocks();
});

const result: LoadTestDto = {
  id: 'lt',
  sessionId: 's',
  runId: 'r',
  toolCallId: 'c',
  projectId: null,
  target: { name: null, origin: 'http://localhost:5199', environment: 'local' },
  status: 'failed',
  error: null,
  durationMs: 30_400,
  vusMax: 10,
  requests: 2_840,
  rate: 93.4,
  failedRate: 0.0123,
  latency: { avg: 21.4, med: 12.1, p90: 48, p95: 88.5, p99: 240.2, max: 610 },
  perRequest: [
    {
      name: 'product list',
      count: 1420,
      failedRate: 0,
      p95: 30.1,
      avg: 12,
      statuses: [{ status: 200, count: 1420 }],
      errorSamples: [],
    },
    {
      name: 'checkout',
      count: 1420,
      failedRate: 0.0246,
      p95: 180.4,
      avg: 31.9,
      statuses: [
        { status: 200, count: 1385 },
        { status: 503, count: 35 },
      ],
      errorSamples: [{ status: 503, body: 'payment service unavailable' }],
    },
  ],
  thresholds: [
    { metric: 'http_req_duration', condition: 'p(95)<200', ok: true, actual: '88.5 ms' },
    { metric: 'http_req_failed', condition: 'rate<0.01', ok: false, actual: '1.23%' },
  ],
  checks: [],
  createdAt: '',
};

describe('load tests', () => {
  it('shows throughput, latency, thresholds and each request', () => {
    render(<LoadTestCard test={result} />);
    const card = screen.getByRole('region', { name: 'Load test: thresholds failed' });
    expect(within(card).getByText('2,840 (93.4/s)')).toBeTruthy();
    expect(within(card).getByText('1.23%')).toBeTruthy();
    expect(within(card).getByText('88.5 ms')).toBeTruthy();
    const thresholds = within(card).getByRole('region', { name: 'Thresholds' });
    expect(within(thresholds).getByRole('img', { name: 'failed' })).toBeTruthy();
    expect(within(thresholds).getByText('measured 1.23%')).toBeTruthy();
    const rows = within(within(card).getByRole('table')).getAllByRole('row');
    expect(rows[2]!.textContent).toBe('checkout1,4202.46%31.9 ms180.4 ms200 × 1,385, 503 × 35');
    expect(within(card).getByRole('list', { name: 'First unexpected answers' }).textContent).toBe(
      'checkout · first 503 answer: payment service unavailable',
    );
  });

  it('shows where the load goes, how much, and the script before it runs', () => {
    const approval: ApprovalDto = {
      id: 'a',
      sessionId: 's',
      runId: 'r',
      projectId: null,
      toolCallId: 'c',
      toolName: 'run_load_test',
      category: 'load_test',
      risk: 'critical',
      title: 'Load test: prod',
      summary: '5 virtual users for 30s against https://shop.example.test.',
      reason: 'check checkout latency',
      details: {
        kind: 'load_test',
        target: { name: 'prod', origin: 'https://shop.example.test', environment: 'production' },
        vus: 5,
        stages: null,
        durationSeconds: 30,
        thinkTimeMs: 1000,
        requests: [
          {
            name: 'home',
            method: 'GET',
            url: 'https://shop.example.test/',
            body: null,
            expectStatus: null,
          },
        ],
        thresholds: ['p(95) < 500 ms'],
        script: "// Generated by Friday\nimport http from 'k6/http';",
        k6: 'k6 v2.3.0 (/usr/bin/k6)',
        limits: { maxVus: 20, maxDurationSeconds: 300 },
        riskReasons: ['Production: real users share this server. Type the target name to approve.'],
      },
      actionHash: 'f'.repeat(64),
      status: 'pending',
      decisionNote: null,
      resultSummary: null,
      createdAt: new Date().toISOString(),
      expiresAt: new Date(Date.now() + 5 * 60_000).toISOString(),
      decidedAt: null,
      confirmationRequired: 'prod',
      grantedBy: null,
    };
    render(<ApprovalCard approval={approval} onDecide={vi.fn()} />);
    expect(screen.getByText('https://shop.example.test')).toBeTruthy();
    expect(screen.getByText('Load').nextElementSibling!.textContent).toMatch(
      /^5 virtual users for 30s/,
    );
    expect(screen.getByText('GET https://shop.example.test/')).toBeTruthy();
    expect(screen.getByLabelText('k6 script').textContent).toContain('Generated by Friday');
    expect((screen.getByRole('button', { name: /^Approve/ }) as HTMLButtonElement).disabled).toBe(
      true,
    );
    expect(
      toolLabel('run_load_test', JSON.stringify({ target: 'prod', vus: 5, duration_seconds: 30 })),
    ).toBe('prod: 5 users, 30s');
  });

  it('lists load-test targets and adds one with its limits', async () => {
    vi.spyOn(api, 'loadTargets').mockResolvedValue({ targets: [] });
    const add = vi.spyOn(api, 'addLoadTarget').mockResolvedValue({} as never);
    render(<LoadTargetSettings />);
    await screen.findByText('No other targets.');
    const form = screen.getByRole('form', { name: 'Add load-test target' });
    fireEvent.change(within(form).getByLabelText('Name'), { target: { value: 'staging' } });
    fireEvent.change(within(form).getByLabelText('Site'), {
      target: { value: 'https://staging.example.test' },
    });
    fireEvent.change(within(form).getByLabelText('Max users'), { target: { value: '30' } });
    fireEvent.change(within(form).getByLabelText('Max min'), { target: { value: '2' } });
    fireEvent.submit(form);
    await waitFor(() => expect(add).toHaveBeenCalled());
    expect(add.mock.calls[0]![0]).toEqual({
      name: 'staging',
      origin: 'https://staging.example.test',
      environment: 'staging',
      maxVus: 30,
      maxDurationSeconds: 120,
    });
  });
});
