import type { ApprovalDto, RunDto, VerificationStatus } from '@friday/shared';
import { ClipboardCheck, FileWarning, GitCommitHorizontal, Loader2, Undo2 } from 'lucide-react';
import { useState } from 'react';
import { cn } from '../lib/cn';
import { RunRecord } from './RunRecord';
import { Badge, type Tone } from './ui/badge';
import { Button } from './ui/button';

const STATUS: Record<VerificationStatus, { label: string; tone: Tone }> = {
  verified: { label: 'verified', tone: 'success' },
  failed: { label: 'verification failed', tone: 'danger' },
  unverified: { label: 'not verified', tone: 'warning' },
  no_changes: { label: 'no file changes', tone: 'neutral' },
};

const CHANGE: Record<string, string> = {
  create: 'created',
  modify: 'modified',
  delete: 'deleted',
  move: 'moved',
};

/**
 * The verification report for one run, generated by the server from its records. Falls back to
 * the plain run record for runs that have no report.
 */
export function RunSummary({
  run,
  approvals,
  onRollback,
}: {
  run: RunDto | undefined;
  approvals: ApprovalDto[];
  onRollback: (runId: string) => Promise<void>;
}) {
  const [busy, setBusy] = useState(false);
  const report = run?.report;
  if (!run || !report) return <RunRecord approvals={approvals} />;

  const status = STATUS[report.status];
  const active = report.files.filter((f) => !f.reverted);
  const skipped = approvals.filter((a) =>
    ['rejected', 'stale', 'failed', 'expired'].includes(a.status),
  );

  return (
    <section
      aria-label="Verification report"
      className="ml-10 space-y-2 rounded-lg border border-zinc-800 bg-zinc-900/40 px-3 py-2.5 text-xs"
    >
      <header className="flex flex-wrap items-center gap-2">
        <ClipboardCheck className="h-3.5 w-3.5 text-zinc-400" aria-hidden />
        <h3 className="font-medium text-zinc-200">Verification report</h3>
        <Badge tone={status.tone}>{status.label}</Badge>
        <span className="text-zinc-500">from Friday’s records, not the model</span>
        {active.length > 0 && (
          <Button
            size="sm"
            variant="ghost"
            className="ml-auto"
            disabled={busy}
            onClick={async () => {
              setBusy(true);
              try {
                await onRollback(run.id);
              } finally {
                setBusy(false);
              }
            }}
          >
            {busy ? (
              <Loader2 className="h-3.5 w-3.5 animate-spin" />
            ) : (
              <Undo2 className="h-3.5 w-3.5" />
            )}
            Roll back this run’s file changes
          </Button>
        )}
      </header>
      <p
        className={cn(
          'text-sm',
          report.status === 'failed'
            ? 'text-red-300'
            : report.status === 'verified'
              ? 'text-emerald-300'
              : 'text-zinc-300',
        )}
      >
        {report.note}
      </p>

      {report.files.length > 0 && (
        <div>
          <h4 className="mb-0.5 text-zinc-500">Files</h4>
          <ul className="space-y-0.5">
            {report.files.map((f, i) => (
              <li key={`${f.path}-${i}`} className="flex flex-wrap items-center gap-2">
                <span
                  className={cn('w-16 shrink-0', f.reverted ? 'text-zinc-600' : 'text-zinc-400')}
                >
                  {f.reverted ? 'undone' : CHANGE[f.change]}
                </span>
                <span
                  className={cn(
                    'font-mono',
                    f.reverted ? 'text-zinc-600 line-through' : 'text-zinc-200',
                  )}
                >
                  {f.fromPath ? `${f.fromPath} → ${f.path}` : f.path}
                </span>
                {f.modifiedSince && (
                  <span className="flex items-center gap-1 text-amber-300">
                    <FileWarning className="h-3 w-3" aria-hidden /> edited elsewhere since
                  </span>
                )}
              </li>
            ))}
          </ul>
        </div>
      )}

      {report.commands.length > 0 && (
        <div>
          <h4 className="mb-0.5 text-zinc-500">Commands</h4>
          <ul className="space-y-0.5">
            {report.commands.map((c, i) => (
              <li key={i} className="flex flex-wrap items-center gap-2">
                <span
                  className={c.exitCode === 0 ? 'text-emerald-400' : 'text-red-400'}
                  aria-label={c.exitCode === 0 ? 'passed' : 'failed'}
                >
                  {c.exitCode === 0 ? '✓' : '✗'}
                </span>
                <span className="font-mono text-zinc-200">{c.title}</span>
                <span className={c.exitCode === 0 ? 'text-zinc-500' : 'text-red-300'}>
                  {c.result}
                </span>
                {c.verification && (
                  <Badge>
                    {c.afterLastChange ? 'check after last change' : 'check before last change'}
                  </Badge>
                )}
              </li>
            ))}
          </ul>
        </div>
      )}

      {report.commits.length > 0 && (
        <div>
          <h4 className="mb-0.5 text-zinc-500">Commits</h4>
          <ul>
            {report.commits.map((c) => (
              <li key={c} className="flex items-center gap-2 font-mono text-zinc-200">
                <GitCommitHorizontal className="h-3 w-3 text-zinc-400" aria-hidden /> {c}
              </li>
            ))}
          </ul>
        </div>
      )}

      {skipped.length > 0 && (
        <div>
          <h4 className="mb-0.5 text-zinc-500">Not executed</h4>
          <ul>
            {skipped.map((a) => (
              <li key={a.id} className="text-zinc-400">
                <span className="font-mono text-zinc-300">{a.title}</span> · {a.status}
                {a.decisionNote ? `: ${a.decisionNote}` : ''}
              </li>
            ))}
          </ul>
        </div>
      )}
    </section>
  );
}
